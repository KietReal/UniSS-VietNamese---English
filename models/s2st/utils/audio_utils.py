import os

def download_augmentation(root_dir: str = "data/augmentation"):
    """Download and prepare both RIR (reverb) and MUSAN (noise) datasets with disk caching."""
    os.makedirs(root_dir, exist_ok=True)
    
    # Native manifest file paths created by Lhotse's prepare_musan and prepare_rir_noise
    musan_manifest = os.path.join(root_dir, "musan_recordings_noise.jsonl.gz")
    rir_manifest = os.path.join(root_dir, "rir_recordings_sim_rir.jsonl.gz")

    # 1. MUSAN Noise Recordings
    if os.path.exists(musan_manifest):
        print(f"[Augmentation] Loading cached MUSAN noise from {musan_manifest}")
        musan_recordings = RecordingSet.from_file(musan_manifest)
    else:
        musan_raw_dir = os.path.join(root_dir, "musan")
        if not os.path.exists(musan_raw_dir):
            print(f"[Augmentation] Downloading MUSAN noise dataset into {root_dir}...")
            musan_raw_dir = download_musan(target_dir=root_dir)
        else:
            print(f"[Augmentation] Using existing extracted 'musan' folder at {musan_raw_dir}")

        musan = prepare_musan(musan_raw_dir, output_dir=root_dir)
        musan_recordings = musan["noise"]["recordings"]

    musan_cuts = CutSet.from_manifests(recordings=musan_recordings).to_eager()

    # 2. RIR (Room Impulse Response) Recordings
    rir_manifest = os.path.join(root_dir, "rir_recordings_sim_rir.jsonl.gz")
    if not os.path.exists(rir_manifest):
        # Check for alternative rir manifest filenames generated by Lhotse
        for fname in os.listdir(root_dir):
            if "rir" in fname.lower() and "recordings" in fname.lower() and fname.endswith(".jsonl.gz"):
                rir_manifest = os.path.join(root_dir, fname)
                break

    if os.path.exists(rir_manifest):
        print(f"[Augmentation] Loading cached RIR recordings from {rir_manifest}")
        rir_recordings = RecordingSet.from_file(rir_manifest)
    else:
        rir_raw_dir = os.path.join(root_dir, "RIRS_NOISES")
        if not os.path.exists(rir_raw_dir):
            print(f"[Augmentation] Downloading RIR noise dataset into {root_dir}...")
            rir_raw_dir = download_rir_noise(target_dir=root_dir)
        else:
            print(f"[Augmentation] Using existing extracted 'RIRS_NOISES' folder at {rir_raw_dir}")

        rirs = prepare_rir_noise(rir_raw_dir, output_dir=root_dir, parts=["sim_rir"])
        rir_recordings = rirs["sim_rir"]["recordings"]

    return rir_recordings, musan_cuts


